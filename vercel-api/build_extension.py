"""Regenerate the browser extension artifacts from vercel-api/public/extension/.

Run after editing anything in that folder:   python vercel-api/build_extension.py
Writes:
  public/extension/instagram-mcp-sync.zip  public zip (no keys; setup needed)
  admin_ui/extension_files.py              embedded copy for the dashboard's pre-configured download
(Vercel only bundles .py files, so the dashboard cannot read public/ at runtime.)
"""
import base64
import pathlib
import zipfile

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE / "public" / "extension"
FILES = ["manifest.json", "manifest-firefox.json", "background.js", "content.js", "fernet.js",
         "options.html", "options.js", "options.css", "icon.png", "README.md"]


def main() -> None:
    with zipfile.ZipFile(SRC / "instagram-mcp-sync.zip", "w", zipfile.ZIP_DEFLATED) as z:
        for name in FILES:
            z.write(SRC / name, arcname=name)
    lines = ['"""GENERATED by vercel-api/build_extension.py. Do not edit by hand.',
             "",
             "Extension files, base64-encoded, so the dashboard can build a pre-configured zip.",
             '"""', "", "FILES = {"]
    for name in FILES:
        b64 = base64.b64encode((SRC / name).read_bytes()).decode()
        lines.append(f"    {name!r}: {b64!r},")
    lines.append("}")
    (HERE / "admin_ui" / "extension_files.py").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"built {len(FILES)} files")


if __name__ == "__main__":
    main()
